"""Pareto / ABC analysis of contribution margin."""
import numpy as np
import pandas as pd


def abc(df, key, cfg, value="cm"):
    """Aggregate ``value`` by ``key`` and classify A/B/C on cumulative share of positive CM.

    Entities are ranked by CM descending. Classes use the cumulative share of the
    sum of *positive* CM: A until a_threshold is reached, B until b_threshold, C for
    the rest with CM >= 0; entities with CM < 0 are "Negative". ``cum_cm_share``
    is the same ranking against net total CM (it exceeds 100% when negative
    entities exist).
    """
    a, b = cfg["abc"]["a_threshold"], cfg["abc"]["b_threshold"]
    keys = [key] if isinstance(key, str) else list(key)
    g = df.groupby(keys, observed=True).agg(revenue=("revenue", "sum"), cogs=("cogs", "sum"),
                                            cm=(value, "sum"), lines=("revenue", "size")).reset_index()
    g = g.sort_values("cm", ascending=False).reset_index(drop=True)
    total, positive = g.cm.sum(), g.cm.clip(lower=0).sum()
    g["cm_margin"] = g.cm / g.revenue
    g["rank"] = np.arange(1, len(g) + 1)
    g["entity_share"] = g["rank"] / len(g)
    g["cm_share"] = g.cm / total
    g["cum_cm_share"] = g.cm.cumsum() / total
    g["cum_positive_cm_share"] = g.cm.clip(lower=0).cumsum() / positive
    prev = g.cum_positive_cm_share.shift(fill_value=0)
    g["abc_class"] = np.select([g.cm < 0, prev < a, prev < b], ["Negative", "A", "B"], "C")
    return g


def concentration(g, shares=(0.01, 0.05, 0.10, 0.20, 0.50)):
    """Share of net and of positive CM generated by the top x% of entities (input = output of abc())."""
    rows = []
    for s in shares:
        n = max(1, int(np.ceil(s * len(g))))
        top = g.cm.iloc[:n]
        rows.append({"top_share": s, "top_n": n, "revenue_share": g.revenue.iloc[:n].sum() / g.revenue.sum(),
                     "cm_share_of_net": top.sum() / g.cm.sum(),
                     "cm_share_of_positive": top.clip(lower=0).sum() / g.cm.clip(lower=0).sum()})
    return pd.DataFrame(rows)


def class_summary(g):
    """Count, revenue and CM per ABC class."""
    s = g.groupby("abc_class").agg(entities=("cm", "size"), revenue=("revenue", "sum"), cm=("cm", "sum"))
    s["entity_share"] = s.entities / s.entities.sum()
    s["revenue_share"] = s.revenue / g.revenue.sum()
    s["cm_share_of_net"] = s.cm / g.cm.sum()
    return s.reindex(["A", "B", "C", "Negative"]).dropna(how="all").reset_index()


def run_all(fact, customers, cfg):
    """Run ABC for every analysis dimension. Returns {dimension: abc table}."""
    f = fact.merge(customers[["CustomerID", "Segment", "StoreBusinessType", "StoreSize", "IncomeBand",
                              "Occupation", "RFMSegment"]], on="CustomerID", how="left")
    dims = {
        "customer": "CustomerID",
        "customer_type": "CustomerType",
        "channel": "Channel",
        "segment": "Segment",
        "store_business_type": "StoreBusinessType",
        "store_size": "StoreSize",
        "income_band": "IncomeBand",
        "occupation": "Occupation",
        "rfm_segment": "RFMSegment",
        "product": ["ProductID", "Product", "Subcategory", "Category"],
        "subcategory": ["Subcategory", "Category"],
        "category": "Category",
        "territory": ["Territory", "TerritoryGroup"],
        "country": "ShipCountry",
        "channel_category": ["Channel", "Category"],
    }
    return {name: abc(f, key, cfg) for name, key in dims.items()}
